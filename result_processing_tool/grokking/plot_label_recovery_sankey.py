#!/usr/bin/env python3
"""Plot a readable Sankey-style summary of noisy-label recovery.

The input is the ``clean_label_recovery_classification.csv`` generated by
``plot_correct_position.py --noise_analysis`` (or the directory containing
that file).  For each split, the figure shows

    train/val -> clean-vs-wrong recorded label -> final model behaviour

The implementation uses only matplotlib, so it also works in the repository's
minimal plotting environment without plotly.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
from matplotlib.path import Path as MplPath
from matplotlib.patches import PathPatch, Rectangle
import numpy as np
import pandas as pd


OUTCOME_ORDER = (
    "clean_label_correct",
    "clean_label_misclassified",
    "wrong_label_recovered",
    "wrong_label_not_recovered",
)

OUTCOME_LABELS = {
    "clean_label_correct": "Clean → correct",
    "clean_label_misclassified": "Clean → wrong",
    "wrong_label_recovered": "Wrong → recovered",
    "wrong_label_not_recovered": "Wrong → not recovered",
}

OUTCOME_COLORS = {
    "clean_label_correct": "#8fd694",
    "clean_label_misclassified": "#e45756",
    "wrong_label_recovered": "#f5a623",
    "wrong_label_not_recovered": "#4c8eda",
    "wrong_label_fitted": "#4c8eda",
    "wrong_label_third_answer": "#9650b5",
    "invalid_prediction": "#a7a7a7",
}

LABEL_COLORS = {
    "clean": "#b7e4c7",
    "wrong": "#f7c873",
}


def _find_csv(input_path: Path) -> Path:
    if input_path.is_file():
        return input_path
    candidate = input_path / "clean_label_recovery_classification.csv"
    if candidate.is_file():
        return candidate
    raise FileNotFoundError(
        f"Could not find clean_label_recovery_classification.csv under {input_path}"
    )


def _detailed_counts(df: pd.DataFrame, split: str) -> dict[str, int]:
    subset = df[df["split"].astype(str).str.lower() == split]
    counts = subset["classification"].value_counts().to_dict()
    return {
        "clean_label_correct": int(counts.get("clean_label_correct", 0)),
        "clean_label_misclassified": int(counts.get("clean_label_misclassified", 0)),
        "wrong_label_recovered": int(counts.get("wrong_label_recovered", 0)),
        "wrong_label_fitted": int(counts.get("wrong_label_fitted", 0)),
        "wrong_label_third_answer": int(counts.get("wrong_label_third_answer", 0)),
        "invalid_prediction": int(counts.get("invalid_prediction", 0)),
    }


def _counts(df: pd.DataFrame, split: str) -> dict[str, int]:
    subset = df[df["split"].astype(str).str.lower() == split]
    wrong = subset["noisy_label_is_wrong"].astype(bool)
    classification = subset["classification"].astype(str)
    return {
        # These graph categories are defined jointly by the true noisy-label
        # state and the model outcome.  In particular, invalid predictions
        # can occur on either clean or wrong labels and must not all be
        # counted as failed recovery.
        "clean_label_correct": int((~wrong & (classification == "clean_label_correct")).sum()),
        "clean_label_misclassified": int((~wrong & (classification != "clean_label_correct")).sum()),
        "wrong_label_recovered": int((wrong & (classification == "wrong_label_recovered")).sum()),
        "wrong_label_not_recovered": int((wrong & (classification != "wrong_label_recovered")).sum()),
    }


def _draw_ribbon(ax, x0: float, x1: float, source: tuple[float, float],
                 target: tuple[float, float], color: str, alpha: float = 0.68):
    """Draw a smooth-ish horizontal Sankey ribbon in normalized axes coords."""
    source_bottom, source_top = source
    target_bottom, target_top = target
    middle = (x0 + x1) / 2.0
    vertices = [
        (x0, source_top),
        (middle, source_top),
        (middle, target_top),
        (x1, target_top),
        (x1, target_bottom),
        (middle, target_bottom),
        (middle, source_bottom),
        (x0, source_bottom),
        (x0, source_top),
    ]
    codes = [
        MplPath.MOVETO,
        MplPath.CURVE3,
        MplPath.CURVE3,
        MplPath.LINETO,
        MplPath.LINETO,
        MplPath.CURVE3,
        MplPath.CURVE3,
        MplPath.LINETO,
        MplPath.CLOSEPOLY,
    ]
    patch = PathPatch(
        MplPath(vertices, codes),
        facecolor=color,
        edgecolor="none",
        alpha=alpha,
        transform=ax.transAxes,
        zorder=1,
    )
    ax.add_patch(patch)


def _layout_nodes(values: dict[str, int], *, top=0.91, bottom=0.08,
                  gap=0.018, min_height=0.014) -> dict[str, tuple[float, float]]:
    total = max(1, sum(values.values()))
    available = top - bottom - gap * max(0, len(values) - 1)
    scale = available / total
    heights = {key: max(min_height, value * scale) for key, value in values.items()}
    # If many tiny categories force the minimum above the available area, scale
    # all nodes down uniformly while retaining the proportions as closely as
    # possible.
    if sum(heights.values()) > available:
        factor = available / sum(heights.values())
        heights = {key: value * factor for key, value in heights.items()}

    result: dict[str, tuple[float, float]] = {}
    cursor = top
    for key, height in heights.items():
        result[key] = (cursor - height, cursor)
        cursor -= height + gap
    return result


def _node(ax, x: float, width: float, span: tuple[float, float], color: str,
          label: str, *, fontsize: float = 9):
    bottom, top = span
    ax.add_patch(
        Rectangle(
            (x, bottom), width, top - bottom,
            transform=ax.transAxes,
            facecolor=color,
            edgecolor="white",
            linewidth=0.8,
            zorder=3,
        )
    )
    ax.text(
        x + width / 2,
        (bottom + top) / 2,
        label,
        transform=ax.transAxes,
        ha="center",
        va="center",
        fontsize=fontsize,
        zorder=4,
    )


def _draw_split(ax, df: pd.DataFrame, split: str):
    subset = df[df["split"].astype(str).str.lower() == split]
    total = len(subset)
    counts = _counts(df, split)
    clean_count = counts["clean_label_correct"] + counts["clean_label_misclassified"]
    wrong_count = counts["wrong_label_recovered"] + counts["wrong_label_not_recovered"]

    source_values = {split: total}
    label_values = {"clean": clean_count, "wrong": wrong_count}
    outcome_values = {key: counts[key] for key in OUTCOME_ORDER}
    source_nodes = _layout_nodes(source_values)
    label_nodes = _layout_nodes(label_values)
    outcome_nodes = _layout_nodes(outcome_values)

    x_source, w_source = 0.025, 0.115
    x_label, w_label = 0.36, 0.14
    x_outcome, w_outcome = 0.775, 0.20

    # First stage: source split -> clean/wrong dataset label.
    source_cursor = source_nodes[split][0]
    for label, value in label_values.items():
        if value <= 0:
            continue
        height = (source_nodes[split][1] - source_nodes[split][0]) * value / total
        source_span = (source_cursor, source_cursor + height)
        target_span = label_nodes[label]
        _draw_ribbon(ax, x_source + w_source, x_label, source_span, target_span,
                     LABEL_COLORS[label], alpha=0.62)
        source_cursor += height

    # Second stage: clean/wrong label -> model outcome.
    source_cursors = {key: label_nodes[key][0] for key in label_nodes}
    target_cursors = {key: outcome_nodes[key][0] for key in outcome_nodes}
    outcome_sources = {
        "clean_label_correct": "clean",
        "clean_label_misclassified": "clean",
        "wrong_label_recovered": "wrong",
        "wrong_label_not_recovered": "wrong",
    }

    for outcome in OUTCOME_ORDER:
        value = outcome_values[outcome]
        if value <= 0:
            continue
        state = outcome_sources[outcome]
        source_span_height = label_nodes[state][1] - label_nodes[state][0]
        source_height = source_span_height * value / label_values[state]
        source_span = (source_cursors[state], source_cursors[state] + source_height)
        target_span_height = outcome_nodes[outcome][1] - outcome_nodes[outcome][0]
        target_height = target_span_height
        target_span = (target_cursors[outcome], target_cursors[outcome] + target_height)
        _draw_ribbon(ax, x_label + w_label, x_outcome, source_span, target_span,
                     OUTCOME_COLORS[outcome], alpha=0.63)
        source_cursors[state] += source_height
        target_cursors[outcome] += target_height

    source_label = f"{split.title()}\n{total:,}"
    _node(ax, x_source, w_source, source_nodes[split], "#6c8ebf", source_label, fontsize=10)
    _node(ax, x_label, w_label, label_nodes["clean"], LABEL_COLORS["clean"],
          f"Clean label\n{clean_count:,}\n({100*clean_count/max(1,total):.1f}%)")
    _node(ax, x_label, w_label, label_nodes["wrong"], LABEL_COLORS["wrong"],
          f"Wrong label\n{wrong_count:,}\n({100*wrong_count/max(1,total):.1f}%)")
    for outcome in OUTCOME_ORDER:
        count = outcome_values[outcome]
        if count <= 0:
            continue
        _node(
            ax, x_outcome, w_outcome, outcome_nodes[outcome],
            OUTCOME_COLORS[outcome],
            f"{OUTCOME_LABELS[outcome]}: {count:,} ({100*count/max(1,total):.1f}%)",
            fontsize=7.8,
        )

    recovery_denominator = wrong_count
    recovery = counts["wrong_label_recovered"] / max(1, recovery_denominator)
    ax.set_title(
        f"{split.title()} split — wrong-label recovery {100*recovery:.1f}% "
        f"({counts['wrong_label_recovered']:,}/{recovery_denominator:,})",
        fontsize=12,
        fontweight="bold",
    )
    ax.text(0.025, 0.025, "Recorded label state", transform=ax.transAxes,
            fontsize=9, color="#555555")
    ax.text(0.775, 0.025, "Deterministic final prediction", transform=ax.transAxes,
            fontsize=9, color="#555555")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.axis("off")


def make_plot(csv_path: Path, output_path: Path) -> Path:
    df = pd.read_csv(csv_path)
    required = {"split", "noisy_label_is_wrong", "classification"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"classification CSV is missing columns: {sorted(missing)}")

    if df["noisy_label_is_wrong"].dtype != bool:
        df["noisy_label_is_wrong"] = (
            df["noisy_label_is_wrong"].astype(str).str.strip().str.lower()
            .map({"true": True, "1": True, "yes": True,
                  "false": False, "0": False, "no": False})
            .fillna(False)
            .astype(bool)
        )
    summary_rows = []
    for split in ("train", "val"):
        subset = df[df["split"].astype(str).str.lower() == split]
        counts = _counts(df, split)
        detailed = _detailed_counts(df, split)
        wrong_total = int(subset["noisy_label_is_wrong"].sum())
        recovered = counts["wrong_label_recovered"]
        summary_rows.append({
            "split": split,
            "total": len(subset),
            "clean_labels": len(subset) - wrong_total,
            "wrong_labels": wrong_total,
            "clean_label_correct": counts["clean_label_correct"],
            "clean_label_misclassified": counts["clean_label_misclassified"],
            "wrong_label_recovered": recovered,
            "wrong_label_fitted": detailed["wrong_label_fitted"],
            "wrong_label_third_answer": detailed["wrong_label_third_answer"],
            "invalid_prediction": detailed["invalid_prediction"],
            "wrong_label_not_recovered": counts["wrong_label_not_recovered"],
            "wrong_label_recovery_rate": recovered / max(1, wrong_total),
        })

    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig, axes = plt.subplots(2, 1, figsize=(18, 14), constrained_layout=True)
    for ax, split in zip(axes, ("train", "val")):
        _draw_split(ax, df, split)
    fig.suptitle("Noisy-label recovery by data split", fontsize=17, fontweight="bold")
    fig.savefig(output_path, dpi=180, bbox_inches="tight")
    fig.savefig(output_path.with_suffix(".pdf"), bbox_inches="tight")
    plt.close(fig)

    summary_path = output_path.with_name(output_path.stem + "_summary.csv")
    pd.DataFrame(summary_rows).to_csv(summary_path, index=False)
    print(f"Saved -> {output_path}")
    print(f"Saved -> {output_path.with_suffix('.pdf')}")
    print(f"Saved -> {summary_path}")
    return output_path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="classification CSV or result folder")
    parser.add_argument("--output", type=Path, default=None,
                        help="output PNG path (default: input folder/clean_label_recovery_sankey.png)")
    args = parser.parse_args()
    csv_path = _find_csv(args.input)
    output_path = args.output or csv_path.with_name("clean_label_recovery_sankey.png")
    make_plot(csv_path, output_path)


if __name__ == "__main__":
    main()
